const TILE_OF = {
  '.': 0, '#': 60, B: 70, H: 1, t: 4, y: 16, Y: 15,
  '~': 95, _: 98, '<': 115, '>': 118, '^': 38,
  w: 74, v: 76, u: 78, 1: 33, 2: 34, 3: 35, T: 6, U: 7, V: 8,
  f: 20, b: 21, F: 22, h: 23, k: 19,
};
const MONSTER_OF = { D: 1, R: 2, L: 3 };

// Positions in the result count from 1, because the engine keeps a wall all the way round the map.
function buildLevel({ name, map }) {
  const tiles = [], monsters = [];
  let door = null, start = null;
  map.forEach((row, r) => {
    if (row.length !== 26) throw new Error(`${name}: row ${r} is ${row.length} long`);
    [...row].forEach((ch, c) => {
      if (ch === 'C') start = [c + 1, r + 1];
      else if (ch === 'M' && !door) door = [c + 1, r + 1];
      else if (MONSTER_OF[ch]) monsters.push([MONSTER_OF[ch], c + 1, r + 1]);
      else if (!(ch in TILE_OF) && ch !== 'M') throw new Error(`${name}: unknown "${ch}" at row ${r}`);
      tiles.push(TILE_OF[ch] || 0);
    });
  });
  if (map.length !== 16) throw new Error(`${name}: ${map.length} rows`);
  return { name, tiles, door, start, monsters };
}

const LEVELS = MAPS.map(buildLevel);
